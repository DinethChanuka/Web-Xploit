def render_header():

    terminal_width = shutil.get_terminal_size(
        fallback=(80, 24)
    ).columns

    width = min(terminal_width, 100)

    data = read_app_data()

    content = Text(justify="center")

    if width >= 75:
        content.append(BANNER.strip("\n"), style="bold primary")
        content.append("\n\n")
        content.append(
            "W E B - X P L O I T\n",
            style="bold text"
        )
        content.append(
            "ADVANCED WEB PENETRATION FRAMEWORK",
            style="secondary"
        )

    else:
        content.append(
            "WEB-XPLOIT\n",
            style="bold primary"
        )
        content.append(
            "ADVANCED WEB PENETRATION FRAMEWORK",
            style="secondary"
        )

    content.append("\n\n")

    console.print(
        Panel(
            Align.center(content),
            border_style="primary",
            box=DOUBLE,
            padding=(1, 2),
            width=width
        ),
        justify="center"
    )

    metadata = Text(justify="center")

    metadata.append("AUTHOR: ", style="muted")
    metadata.append(data["author"], style="success")

    metadata.append("     VERSION: ", style="muted")
    metadata.append(data["version"], style="primary")

    metadata.append("\nLAST UPDATED: ", style="muted")
    metadata.append(data["last_updated_at"], style="success")

    console.print(
        Panel(
            Align.center(metadata),
            border_style="primary",
            box=DOUBLE,
            width=width
        ),
        justify="center"
    )
